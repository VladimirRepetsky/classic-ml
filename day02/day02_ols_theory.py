print("""
   Чтобы учесть свободный член, добавляем столбец единиц:

   X_b = [1 | X]

   где первый столбец — все единицы.

   Тогда нормальное уравнение:

   w = (X_bᵀ · X_b)⁻¹ · X_bᵀ · y

   где:
   • X_bᵀ — транспонированная матрица
   • (X_bᵀ · X_b)⁻¹ — обратная матрица
   • Результат: вектор весов, где первый элемент — свободный член

   ⚠️ На практике вместо обращения матрицы используют
      решение системы линейных уравнений:

   (X_bᵀ · X_b) · w = X_bᵀ · y
   → решаем через np.linalg.solve()

   Это численно устойчивее и быстрее.
""")


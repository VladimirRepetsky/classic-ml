print("""
1. МОДЕЛЬ ЛИНЕЙНОЙ РЕГРЕССИИ

   ŷ = w₁·x₁ + w₂·x₂ + ... + wₙ·xₙ + b

   где:
   • ŷ (y-hat) — предсказание модели
   • x₁, x₂, ..., xₙ — признаки
   • w₁, w₂, ..., wₙ — веса (коэффициенты)
   • b — свободный член (смещение, интерсепт)

   В матричной форме:
   
   ŷ = X · w + b

   где:
   • X — матрица признаков (n_samples × n_features)
   • w — вектор весов (n_features,)
   • b — скаляр

2. ФУНКЦИЯ ПОТЕРЬ (что мы минимизируем)

   Мы хотим, чтобы предсказания модели были как можно ближе
   к реальным значениям. Меру ошибки называем функцией потерь.

   Для регрессии используем среднеквадратичную ошибку (MSE):

   MSE(w, b) = (1/n) · Σᵢ (yᵢ - ŷᵢ)²
             = (1/n) · Σᵢ (yᵢ - (w·xᵢ + b))²

   где:
   • n — количество образцов
   • yᵢ — реальное значение
   • ŷᵢ — предсказание модели

3. ЗАДАЧА ОПТИМИЗАЦИИ

   Найти такие веса w и смещение b, которые минимизируют функцию потерь:

   w*, b* = argmin   MSE(w, b)
            w, b

   Это задача оптимизации. Есть два пути её решения:

   ПУТЬ A: АНАЛИТИЧЕСКОЕ РЕШЕНИЕ (нормальное уравнение)
   ─────────────────────────────────────────────────────
   • Решается за одну операцию
   • Точное решение
   • Работает, когда признаков немного (< 10 000)
   • Формула: w = (XᵀX)⁻¹Xᵀy
   • Используется в sklearn.linear_model.LinearRegression

   ПУТЬ B: ИТЕРАТИВНАЯ ОПТИМИЗАЦИЯ (градиентный спуск)
   ─────────────────────────────────────────────────────
   • Шаги к минимуму постепенно
   • Приближённое решение (но достаточно точное)
   • Работает на любых данных (миллионы признаков)
   • Требует настройки скорости обучения
   • Используется в нейросетях (глубокое обучение)

4. ПОЧЕМУ MSE?

   • Квадрат ошибки делает большие ошибки ещё больше
   • Дифференцируема → можно взять производную
   • Выпукла → единственный глобальный минимум
   • Математически удобна

5. СВЯЗЬ С ДНЁМ 1

   Когда ты пишешь:
       model = LinearRegression()
       model.fit(X_train, y_train)

   Внутри происходит:
       1. К матрице признаков добавляется столбец единиц
          (для учёта свободного члена)
       2. Решается нормальное уравнение через
          np.linalg.lstsq(X_b, y)
       3. Веса сохраняются в model.coef_ и model.intercept_
""")


print("""
   Представь, что ты стоишь на холме в тумане и хочешь
   спуститься в самую низкую точку. Ты не видишь всей
   поверхности, но можешь определить направление наибольшего
   спуска под ногами.

   Алгоритм:
   1. Сделай маленький шаг в направлении наибольшего спуска
   2. Повтори

   Математически:
   • Градиент — вектор наибольшего возрастания функции
   • Мы идём в противоположном направлении

   Формула обновления весов:

   w ← w - α · ∂MSE/∂w
   b ← b - α · ∂MSE/∂b

   где:
   • α (альфа) — скорость обучения (размер шага)
   • ∂MSE/∂w — градиент функции потерь по весам

   Градиенты для MSE:

   ∂MSE/∂w = (2/n) · Xᵀ · (Xw + b - y)
   ∂MSE/∂b = (2/n) · Σ(Xw + b - y)

   Повторяем до сходимости.
""")


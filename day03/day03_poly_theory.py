print("""
1. ПРОБЛЕМА ЛИНЕЙНОЙ МОДЕЛИ

   Линейная регрессия строит прямую линию:
   
       ŷ = w₁·x + b
   
   Но реальные зависимости часто нелинейны:
   • Цена дома растёт с доходом, но с замедлением
   • Температура влияет на спрос на мороженое колоколообразно
   • Возраст и доход связаны нелинейно

   Прямая линия не может описать такие зависимости.

2. РЕШЕНИЕ: ПОЛИНОМИАЛЬНЫЕ ПРИЗНАКИ

   Идея: добавить новые признаки — степени исходного признака.
   
   Было:
       ŷ = w₁·x + b
   
   Стало (степень 2):
       ŷ = w₁·x + w₂·x² + b
   
   Стало (степень 3):
       ŷ = w₁·x + w₂·x² + w₃·x³ + b
   
   Модель остаётся ЛИНЕЙНОЙ ПО ПАРАМЕТРАМ (весам).
   Мы просто добавили новые признаки.

3. КЛЮЧЕВОЙ ИНСАЙТ

   Полиномиальная регрессия — это ВСЁ ЕЩЁ ЛИНЕЙНАЯ РЕГРЕССИЯ.
   
   Модель линейна по весам:
       ŷ = w₁·x₁ + w₂·x₂ + w₃·x₃ + b
   
   где:
       x₁ = x
       x₂ = x²
       x₃ = x³
   
   Мы не меняем модель. Мы меняем ПРИЗНАКИ.

4. СТЕПЕНЬ ПОЛИНОМА — ГИПЕРПАРАМЕТР

   Степень полинома (1, 2, 3, ...) — это гиперпараметр.
   
   Гиперпараметры:
   • НЕ выучиваются моделью из данных
   • Задаются ДО обучения
   • Подбираются через валидацию
   
   Слишком малая степень → недообучение
   Слишком большая степень → переобучение

5. ПЕРЕОБУЧЕНИЕ И НЕДООБУЧЕНИЕ

   НЕДООБУЧЕНИЕ (высокое смещение):
   • Модель слишком простая
   • Не улавливает закономерности
   • Высокая ошибка и на тренинге, и на тесте
   
   ПЕРЕОБУЧЕНИЕ (высокая дисперсия):
   • Модель слишком сложная
   • Запоминает шум в данных
   • Низкая ошибка на тренинге, высокая на тесте
   
   ХОРОШАЯ МОДЕЛЬ:
   • Баланс между простотой и сложностью
   • Низкая ошибка и на тренинге, и на тесте
""")

